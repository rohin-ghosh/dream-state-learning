def verify_phase_lattice(
    requirements: dict[str, Any], science: dict[str, Any], systems: dict[str, Any]
) -> list[dict[str, Any]]:
    cardinality = requirements["cardinality_contract"]
    contract = requirements["phase_row_contract"]
    expected = expected_phase_rows(requirements)
    assert_equal(len(contract["family_ids_in_order"]), 21, "family count")
    assert_equal(len(contract["phase_profiles_in_order"]), 6, "phase count")
    assert_equal(len(expected), 126, "derived phase-row count")
    assert_equal(cardinality["acceptance_family_count"], 21, "declared family count")
    assert_equal(cardinality["phase_count"], 6, "declared phase count")
    assert_equal(cardinality["phase_row_count"], 126, "declared row count")

    science_contract = science["acceptance_obligation_contract"]
    systems_contract = systems["acceptance_lattice"]
    family_ids = contract["family_ids_in_order"]
    assert_equal(
        [item["family_id"] for item in science_contract["families"]],
        family_ids,
        "scientific family order",
    )
    assert_equal(
        [item["test_id"] for item in systems_contract["families"]],
        family_ids,
        "systems family order",
    )
    assert_equal(science_contract["phase_profiles"], contract["phase_profiles_in_order"], "scientific phase profiles")
    system_phase_projection = [
        {
            key: phase[key]
            for key in (
                "phase_id", "producer_action_id",
                "required_nonempty_root_fields",
                "exact_first_downstream_consumer_action_ids",
            )
        }
        for phase in systems_contract["phase_specs"]
    ]
    assert_equal(system_phase_projection, contract["phase_profiles_in_order"], "systems phase profiles")

    science_rows = science_contract["phase_rows"]
    systems_rows = systems_contract["rows"]
    assert_equal(len(science_rows), 126, "scientific row count")
    assert_equal(len(systems_rows), 126, "systems row count")
    assert_equal(ids(science_rows, "row_id", "scientific row ID"), [row["row_id"] for row in expected], "scientific row IDs")
    assert_equal(ids(systems_rows, "row_id", "systems row ID"), [row["row_id"] for row in expected], "systems row IDs")
    assert_equal(ids(science_rows, "receipt_id", "scientific receipt ID"), [row["receipt_id"] for row in expected], "scientific receipt IDs")
    assert_equal(ids(systems_rows, "receipt_id", "systems receipt ID"), [row["receipt_id"] for row in expected], "systems receipt IDs")

    for target, scientific, system in zip(expected, science_rows, systems_rows):
        for key in (
            "row_id", "receipt_id", "family_id", "phase_id",
            "producer_action_id", "exact_first_downstream_consumer_action_ids",
        ):
            assert_equal(scientific[key], target[key], f"science {target['row_id']} {key}")
            assert_equal(system[key], target[key], f"systems {target['row_id']} {key}")
        assert_equal(
            scientific["required_nonempty_root_fields"],
            target["required_nonempty_root_fields"],
            f"science {target['row_id']} required roots",
        )
        for required in target["required_nonempty_root_fields"]:
            slot_key = required[:-1] + "_slots" if required.endswith("s") else required + "_slots"
            slots = system.get(slot_key)
            if required == "review_root":
                slots = [system.get("review_root_requirement")]
            if not slots or slots == ["NOT_APPLICABLE"]:
                raise ValueError(f"systems row lacks required {required}: {target['row_id']}")
        if system["prospective_state"] != "UNPRODUCED_UNEVALUATED":
            raise ValueError(f"nonprospective systems row: {target['row_id']}")

    manifests = systems_contract["phase_manifests"]
    assert_equal(len(manifests), 6, "phase-manifest count")
    for phase, manifest in zip(contract["phase_profiles_in_order"], manifests):
        phase_id = phase["phase_id"]
        phase_rows = [row for row in expected if row["phase_id"] == phase_id]
        assert_equal(manifest["manifest_id"], f"V8_PHASE_MANIFEST__{phase_id}", f"{phase_id} manifest ID")
        assert_equal(manifest["expected_row_ids"], [row["row_id"] for row in phase_rows], f"{phase_id} manifest rows")
        assert_equal(manifest["expected_receipt_ids"], [row["receipt_id"] for row in phase_rows], f"{phase_id} manifest receipts")
        assert_equal(manifest["row_count"], 21, f"{phase_id} manifest row count")
        assert_equal(manifest["producer_action_ids"], [phase["producer_action_id"]], f"{phase_id} manifest producer")
        assert_equal(manifest["first_consumer_action_ids"], phase["exact_first_downstream_consumer_action_ids"], f"{phase_id} manifest consumers")
        if manifest["prospective_state"] != "UNPRODUCED_UNEVALUATED":
            raise ValueError(f"nonprospective phase manifest: {phase_id}")
    return expected


def verify_registry_and_dag(requirements: dict[str, Any], systems: dict[str, Any]) -> None:
    registry = systems["canonical_registry_source"]
    dag = systems["finite_action_dag"]
    required = requirements["required_v8_object_identities"]

    lifetimes = set(ids(registry["lifetime_classes"], "lifetime_id", "lifetime ID"))
    sources = set(ids(registry["registered_sources"], "source_id", "source ID"))
    principals = set(unique(registry["registered_principals"], "principal ID"))
    operations = set(ids(registry["operations"], "operation", "operation ID"))
    artifacts_list = registry["artifact_definitions"]
    artifacts = {item["artifact_class"]: item for item in artifacts_list}
    if len(artifacts) != len(artifacts_list):
        raise ValueError("duplicate artifact class")
    schema_defs = set(ids(registry["schema_definitions"], "schema_id", "schema ID"))
    actions_list = dag["control_actions"]
    actions = {item["action_id"]: item for item in actions_list}
    if len(actions) != len(actions_list):
        raise ValueError("duplicate action ID")

    if not set(required["lifetime_ids_that_must_resolve"]) <= lifetimes:
        raise ValueError("required immutable lifetime is unresolved")
    if not set(required["artifact_class_ids"]) <= set(artifacts):
        raise ValueError("required artifact class is unresolved")
    if not set(required["operation_ids"]) <= operations:
        raise ValueError("required operation is unresolved")
    if not set(required["schema_ids"]) <= schema_defs:
        raise ValueError("required exact schema is unresolved")
    if not set(required["principal_ids"]) <= principals | sources:
        raise ValueError("required principal/source is unresolved")

    required_actions: set[str] = set()
    for field in (
        "phase_producer_action_ids", "phase_boundary_action_ids",
        "candidate_and_reporting_action_ids", "release_chain_action_ids_in_order",
    ):
        required_actions.update(required[field])
    if not required_actions <= set(actions):
        raise ValueError(f"required action IDs unresolved: {sorted(required_actions - set(actions))}")
    assert_equal(
        systems["release_chain"]["ordered_actions"],
        required["release_chain_action_ids_in_order"],
        "release action order",
    )

    known_producers = principals | sources
    for item in artifacts_list:
        if item["lifetime_id"] not in lifetimes:
            raise ValueError(f"unresolved lifetime on {item['artifact_class']}")
        if item["sole_producer_id"] not in known_producers:
            raise ValueError(f"unresolved producer on {item['artifact_class']}")
        if not item["payload_schema_id"]:
            raise ValueError(f"missing payload schema on {item['artifact_class']}")

    source_projection: dict[str, list[str]] = {source: [] for source in sources}
    for item in artifacts_list:
        if item["sole_producer_id"] in sources:
            source_projection[item["sole_producer_id"]].append(item["artifact_class"])
    declared_projection = {
        item["source_id"]: item["produced_artifact_classes"]
        for item in registry["materialized_source_product_manifests"]
    }
    assert_equal(set(declared_projection), sources, "source-product manifest source set")
    for source in sources:
        assert_equal(sorted(declared_projection[source]), sorted(source_projection[source]), f"source-product projection {source}")

    phase_manifest_ids = {
        item["manifest_id"] for item in systems["acceptance_lattice"]["phase_manifests"]
    }
    producer_for: dict[str, dict[str, Any]] = {}
    for action in actions_list:
        if action["principal_id"] not in principals | sources:
            raise ValueError(f"unregistered action principal/source: {action['action_id']}")
        for product in action["produces_receipt_ids"]:
            # A class can be emitted by distinct phase-specific instances.  The
            # sealed instance manifest supplies the unique concrete identity.
            producer_for.setdefault(product, action)
        for prerequisite in action["prerequisite_receipt_ids"]:
            if prerequisite not in artifacts and prerequisite not in phase_manifest_ids:
                raise ValueError(f"unresolved prerequisite {prerequisite} on {action['action_id']}")
    for action in actions_list:
        for prerequisite in action["prerequisite_receipt_ids"]:
            producer = producer_for.get(prerequisite)
            if producer and producer["topological_rank"] >= action["topological_rank"]:
                raise ValueError(f"noncausal prerequisite {prerequisite} on {action['action_id']}")

    if systems["candidate_closure"]["operation"] != "SEAL_CANDIDATE_CLOSURE_ATOMIC":
        raise ValueError("candidate closure is not atomic")
    if systems["promotion_cas"]["operation"] != "PROMOTE_CAS_ATOMIC":
        raise ValueError("promotion operation is not atomic CAS")
    if systems["release_chain"]["transfer_operation"] != "TRANSFER_OPAQUE":
        raise ValueError("release is not opaque transfer")
    if systems["finite_action_dag"]["first_consumer_map"] != {
        item["phase_id"]: item["exact_first_downstream_consumer_action_ids"]
        for item in requirements["phase_row_contract"]["phase_profiles_in_order"]
    }:
        raise ValueError("DAG first-consumer map differs from integration contract")



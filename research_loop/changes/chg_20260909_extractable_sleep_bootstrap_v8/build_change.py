def _visibility_elements(systems: dict[str, Any]) -> list[dict[str, Any]]:
    """Materialize object-specific visibility elements from the exact source.

    V7's defect was a principal-by-*capability category* matrix.  V8 instead
    enumerates each actual registry/DAG/test/action/receipt object and every
    concrete producer/consumer bridge presently defined.  A later sealed
    invocation sub-DAG regenerates the same structure for every dynamic action
    instance; no future root count is guessed here.
    """
    registry = systems["canonical_registry_source"]
    dag = systems["finite_action_dag"]
    lattice = systems["acceptance_lattice"]
    actions = {a["action_id"]: a for a in dag["control_actions"]}
    principals = set(registry["registered_principals"])
    sources = {s["source_id"] for s in registry["registered_sources"]}
    stages = principals | sources | {"EXTERNAL_HUMAN_OBSERVER"}
    visibility_sealer = "G0_VISIBILITY_MANIFEST_SEALER"

    elements: dict[str, dict[str, Any]] = {}

    def add(category: str, object_id: str, *, producers: Iterable[str] = (),
            consumers: Iterable[str] = (), observers: Iterable[str] = ()) -> None:
        base_id = f"{category}::{object_id}"
        row = elements.setdefault(base_id, {
            "base_id": base_id,
            "category": category,
            "object_id": object_id,
            "producers": set(),
            "consumers": set(),
            "observers": {visibility_sealer},
        })
        row["producers"].update(producers)
        row["consumers"].update(consumers)
        row["observers"].update(observers)

    # One content root equality-binds all prose/rules that do not carry their
    # own semantic ID; named objects below make the authority-bearing universe
    # independently enumerable.
    add("systems_core", sha256(SYSTEMS_PATH),
        producers=["G0_REGISTRY_GENERATOR"],
        consumers=["G0_ACTION_DAG_GENERATOR", "G0_VISIBILITY_MANIFEST_SEALER"])

    for principal in registry["registered_principals"]:
        add("principal", principal, producers=["G0_REGISTRY_GENERATOR"],
            consumers=[principal])
    for source in sources:
        add("source", source, producers=["G0_REGISTRY_GENERATOR"],
            consumers=[source])
    for lifetime in registry["lifetime_classes"]:
        add("lifetime", lifetime["lifetime_id"],
            producers=["G0_REGISTRY_GENERATOR"])
    for operation in registry["operations"]:
        op = operation["operation"]
        add("operation", op, producers=["G0_REGISTRY_GENERATOR"])
        add("operation_request_schema", operation["request_schema_id"],
            producers=["G0_REGISTRY_GENERATOR"])
        add("operation_result_schema", operation["result_schema_id"],
            producers=["G0_REGISTRY_GENERATOR"])

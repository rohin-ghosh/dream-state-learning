def validate_document(
    doc: dict[str, Any], requirements: dict[str, Any], science: dict[str, Any],
    systems: dict[str, Any], expected_rows: list[dict[str, Any]],
) -> None:
    from research_loop.architecture_intake import _validate_schema

    schema = load_json(ROOT / "research_loop/schemas/architecture_change.schema.json")
    errors = _validate_schema(doc, schema, schema)
    if errors:
        raise ValueError("architecture-change schema failure:\n- " + "\n- ".join(errors))

    assert_equal(doc["state"], "proposed", "proposal state")
    assert_equal([entry["path"] for entry in doc["context_files"]], [entry[0] for entry in INPUTS], "context path set/order")
    for entry in doc["context_files"]:
        assert_equal(sha256(ROOT / entry["path"]), entry["sha256"], f"rendered context hash {entry['path']}")

    test_ids = ids(doc["acceptance_tests"], "test_id", "top-level acceptance-test ID")
    assert_equal(test_ids, [row["row_id"] for row in expected_rows], "top-level 126-row ID order")
    assert_equal(len(test_ids), 126, "top-level acceptance-test count")
    phase_for = {row["row_id"]: row["phase_id"] for row in expected_rows}
    for test in doc["acceptance_tests"]:
        phase = phase_for[test["test_id"]]
        assert_equal(test["required_before"], PHASE_REQUIRED_BEFORE[phase], f"required_before {test['test_id']}")
        if "UNPRODUCED_UNEVALUATED" not in test["setup"]:
            raise ValueError(f"row omits prospective state: {test['test_id']}")

    matrix = doc["visibility_matrix"]
    visibility_elements = _visibility_elements(systems)
    expected_items = [
        f"UNIVERSE__{element['base_id']}__{channel}"
        for element in visibility_elements
        for channel in systems["visibility"]["channels"]
    ]
    expected_stages = list(dict.fromkeys(
        systems["canonical_registry_source"]["registered_principals"]
        + [
            source["source_id"]
            for source in systems["canonical_registry_source"]["registered_sources"]
        ]
        + ["EXTERNAL_HUMAN_OBSERVER"]
    ))
    assert_equal(matrix["information_items"], expected_items, "object-specific systems-derived visibility universe")
    assert_equal(matrix["stages"], expected_stages, "object-specific systems-derived visibility stages")
    expected_pairs = {(item, stage) for item in matrix["information_items"] for stage in matrix["stages"]}
    actual_pairs = [(cell["information_id"], cell["stage_id"]) for cell in matrix["cells"]]
    assert_equal(len(actual_pairs), len(expected_pairs), "visibility cell count")
    assert_equal(set(actual_pairs), expected_pairs, "visibility exact cartesian product")
    if len(actual_pairs) != len(set(actual_pairs)):
        raise ValueError("duplicate visibility cells")

    organism = systems["organism_boundary"]
    assert_equal(organism["functions_exactly"], ["THINK", "DREAM", "SLEEP"], "systems organism function set")
    assert_equal(list(science["organism_boundary"]["functions"]), ["THINK", "DREAM", "SLEEP"], "scientific organism function set")
    cognitive_nodes = [node["node_id"] for node in doc["graph_delta"]["nodes"] if node["node_id"] in {"THINK", "DREAM", "SLEEP"}]
    assert_equal(cognitive_nodes, ["THINK", "DREAM", "SLEEP"], "proposal cognitive nodes")
    assert_equal(requirements["cardinality_contract"]["formal_estimand_ids"], ["Delta_R", "Delta_F", "Delta_E"], "formal estimands")
    assert_equal(science["formal_estimands"]["primary_estimand_count"], 3, "scientific estimand count")

    artifact_classes = {item["artifact_class"] for item in systems["canonical_registry_source"]["artifact_definitions"]}
    for item in doc["loop_delta"]["loops"]:
        unknown = set(item["reads"] + item["writes"]) - artifact_classes
        if unknown:
            raise ValueError(f"loop {item['loop_id']} uses unregistered artifact classes: {sorted(unknown)}")

    serialized = json.dumps(doc, sort_keys=True)
    for forbidden in requirements["required_v8_object_identities"]["forbidden_stale_ids"]:
        if forbidden in serialized:
            raise ValueError(f"proposal contains forbidden stale ID: {forbidden}")
    for prohibited in ("192-example", "habit_count", "32 examples per habit", "six-habit"):
        if prohibited.lower() in serialized.lower():
            raise ValueError(f"proposal prematurely fixes bootstrap content: {prohibited}")
    if doc["human_boundary"]["forbidden_before_approval"] != requirements["authority_boundary"]["forbidden_now"]:
        raise ValueError("human boundary does not repeat exact forbidden scope")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--stdout", action="store_true", help="render compact JSON without writing")
    parser.add_argument("--compact", action="store_true", help="write compact JSON")
    args = parser.parse_args()
    doc = build()
    if args.stdout:
        print(json.dumps(doc, sort_keys=False, separators=(",", ":")))
        return
    rendered = json.dumps(doc, separators=(",", ":")) if args.compact else json.dumps(doc, indent=2)
    OUT.write_text(rendered + "\n")
    from research_loop.architecture_intake import validate_change
    validate_change(ROOT, OUT)


if __name__ == "__main__":
    main()

def arr(items, *, minimum=0, maximum=None, unique=False):
    result = {"type": "array", "items": items, "minItems": minimum}
    if maximum is not None:
        result["maxItems"] = maximum
    if unique:
        result["uniqueItems"] = True
    return result


def enum(*values):
    return {"enum": list(values)}


def integer(minimum=0, maximum=None):
    result = {"type": "integer", "minimum": minimum}
    if maximum is not None:
        result["maximum"] = maximum
    return result


def closed(required, properties, *, one_of=None):
    result = {
        "type": "object",
        "additionalProperties": False,
        "required": list(required),
        "properties": properties,
    }
    if one_of:
        result["oneOf"] = one_of
    return result


def top(contract, hash_field, fields, *, one_of=None):
    properties = {
        "contract": {"const": contract},
        "schema_version": {"const": SCHEMA_VERSION},
        **fields,
        hash_field: H,
    }
    return closed(properties, properties, one_of=one_of)


def aref(role=None, artifact_types=None, ordinal=None):
    role_schema = {"const": role} if role else SYM
    type_schema = (
        enum(*artifact_types)
        if artifact_types
        else SYM
    )
    ordinal_schema = {"const": ordinal} if ordinal is not None else integer()
    return closed(
        ["role", "ordinal", "artifact_type", "sha256"],
        {
            "role": role_schema,
            "ordinal": ordinal_schema,
            "artifact_type": type_schema,
            "sha256": H,
        },
    )


def run_ref(role=None, artifact_types=None, ordinal=None):
    """Typed semantic reference whose target must belong to the same run."""
    base = aref(role, artifact_types, ordinal)
    base["required"].insert(0, "run_id")
    base["properties"]["run_id"] = ID
    return base


def exact_refs(*roles):
    prefix = [aref(role, types, index) for index, (role, types) in enumerate(roles)]
    return {
        "type": "array",
        "prefixItems": prefix,
        "items": False,
        "minItems": len(prefix),
        "maxItems": len(prefix),
    }


def byte_ref(role=None, ordinal=None):
    return closed(
        ["role", "ordinal", "media_type", "relative_path", "byte_length", "raw_sha256"],
        {
            "role": {"const": role} if role else SYM,
            "ordinal": {"const": ordinal} if ordinal is not None else integer(),
            "media_type": SYM,
            "relative_path": {"type": "string", "pattern": "^(?!/)(?!.*(?:^|/)\\.\\.(?:/|$)).+$"},
            "byte_length": integer(),
            "raw_sha256": H,
        },
    )


def nullable(schema):
    return {"oneOf": [schema, {"type": "null"}]}



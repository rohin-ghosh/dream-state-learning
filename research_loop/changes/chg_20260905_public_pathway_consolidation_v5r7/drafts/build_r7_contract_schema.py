def collect_typed_refs(node, *, active=None, memo=None, cardinality="ONE"):
    """Resolve local $defs recursively to a fixed point, rejecting cycles.

    Cycles in the *schema vocabulary* are legal, so an active-stack hit stops
    traversal of that edge; semantic artifact cycles are tested separately.
    """
    active = set() if active is None else active
    memo = {} if memo is None else memo
    found = set()
    if isinstance(node, dict):
        local_ref = node.get("$ref", "")
        if local_ref.startswith("#/$defs/"):
            name = local_ref.rsplit("/", 1)[-1]
            key = (name, cardinality)
            if key in memo:
                return set(memo[key])
            if name in active:
                return set()
            if name not in defs:
                raise SystemExit(f"unresolved local schema ref: {local_ref}")
            active.add(name)
            resolved = collect_typed_refs(defs[name], active=active, memo=memo,
                                          cardinality=cardinality)
            active.remove(name)
            memo[key] = frozenset(resolved)
            return set(resolved)
        props = node.get("properties", {})
        if {"role", "ordinal", "artifact_type", "sha256"}.issubset(props):
            role_schema = props["role"]
            type_schema = props["artifact_type"]
            ordinal_schema = props["ordinal"]
            roles = [role_schema["const"]] if "const" in role_schema else role_schema.get("enum", [])
            types = [type_schema["const"]] if "const" in type_schema else type_schema.get("enum", [])
            ordinal = ordinal_schema.get("const", "VARIABLE")
            for role in roles:
                for artifact_type in types:
                    found.add((role, artifact_type, ordinal, cardinality))
            return found
        for key, value in node.items():
            next_cardinality = cardinality
            if key in {"items", "prefixItems"}:
                next_cardinality = "VARIABLE" if key == "items" else "ORDERED_EXACT"
            found.update(collect_typed_refs(value, active=active, memo=memo,
                                            cardinality=next_cardinality))
    elif isinstance(node, list):
        for value in node:
            found.update(collect_typed_refs(value, active=active, memo=memo,
                                            cardinality=cardinality))
    return found



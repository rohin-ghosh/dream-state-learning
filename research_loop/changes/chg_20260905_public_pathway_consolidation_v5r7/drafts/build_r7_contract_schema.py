def transition(result, family, index_rule="NONE", terminal=None,
               *, consume=False, advance=False, endpoint="NONE",
               predicate="ANY_0_2", update=None, normalized=None):
    if update is None:
        update = "INCREMENT" if result == "ERROR" else (
            "PRESERVE" if "MISSING" in result or result in {"FINALIZE", "FLUSH_SKIPPED_REJECTED"} else "RESET_ZERO")
    return {
        "accepted_result": result,
        "counter_predicate": predicate,
        "counter_update": update,
        "normalized_result": normalized or result,
        "next_phase": {"family": family, "index_rule": index_rule,
                       "terminal_reason": terminal},
        "consume_call": consume,
        "advance_once": advance,
        "retry_allowed": False,
        "endpoint_effect": endpoint,
    }



    for stage_name in visibility["stages"]:
        raw = visibility["matrix"][info][stage_name]
        if ":" in raw:
            level, rationale = raw.split(":", 1)
        else:
            level, rationale = raw, "No dependency or influence is permitted."
        level = level.strip()
        rationale = rationale.strip()
        if level not in {"visible", "derived_only", "forbidden"} or not rationale:
            raise SystemExit(f"invalid visibility cell {info}/{stage_name}: {raw}")

"""
Experiment 2.5 — does the trained-value result survive MODEL-CLASS MISMATCH?

Exp 2 caveat: data was linear-logistic and the learner was logistic regression —
matched, so "training works" was partly the estimator fitting its own form. Here
the outcome is generated by a NONLINEAR (conjunctive) causal rule and we fit with
(a) linear logistic regression [MISMATCHED] and (b) a small MLP [nonlinear].
Per-fact value = occlusion attribution (avg change in predicted success when a
fact is forced on vs off) — works for any model.

Nonlinear causal structure: success depends on satisfied "recipes" — specific
PAIRS of structural facts that must BOTH be present (AND/interaction). Linear
models cannot represent AND exactly. Details (confounded + random) have no causal
role. Frequency held uninformative (equal marginals). Value model never sees the
label.

Question: does outcome-training still separate structural from confounded/random
details when the learner is wrong about the functional form? And does a nonlinear
learner recover what the linear one misses?

numpy only, CPU.
"""

from __future__ import annotations

import numpy as np

N_STRUCT, N_CONF, N_RAND = 15, 15, 20
N_FACTS = N_STRUCT + N_CONF + N_RAND
STRUCT = np.arange(0, N_STRUCT)
CONF = np.arange(N_STRUCT, N_STRUCT + N_CONF)
RAND = np.arange(N_STRUCT + N_CONF, N_FACTS)
IS_STRUCT = np.zeros(N_FACTS, bool); IS_STRUCT[STRUCT] = True
IS_CONF = np.zeros(N_FACTS, bool); IS_CONF[CONF] = True
IS_RAND = np.zeros(N_FACTS, bool); IS_RAND[RAND] = True


def gen(rng, n_ep, p=0.4, a=0.7, n_recipes=10):
    # recipes = random pairs of structural facts; success if ANY recipe fully present
    recipes = [tuple(rng.choice(N_STRUCT, size=2, replace=False)) for _ in range(n_recipes)]
    b = (p - p * a) / (1 - p)
    X = np.zeros((n_ep, N_FACTS))
    for e in range(n_ep):
        s = (rng.random(N_STRUCT) < p).astype(float)
        X[e, STRUCT] = s
        c = np.where(s == 1, rng.random(N_STRUCT) < a, rng.random(N_STRUCT) < b)
        X[e, CONF] = c.astype(float)
        X[e, RAND] = (rng.random(N_RAND) < p).astype(float)
    sat = np.zeros(n_ep)
    for (i, j) in recipes:
        sat += (X[:, i] * X[:, j])           # count satisfied recipes (nonlinear AND)
    logit = np.clip(1.6 * (sat - 1.0), -30, 30)
    y = (rng.random(n_ep) < 1 / (1 + np.exp(-logit))).astype(float)
    return X, y


def fit_logreg(X, y, l2=1.0, iters=500, lr=0.5):
    n, d = X.shape; w = np.zeros(d); b = 0.0
    for _ in range(iters):
        z = np.clip(X @ w + b, -30, 30)
        g = 1 / (1 + np.exp(-z)) - y
        w -= lr * (X.T @ g / n + l2 * w / n); b -= lr * g.mean()
    return lambda Z: 1 / (1 + np.exp(-np.clip(Z @ w + b, -30, 30)))


def fit_mlp(X, y, H=24, iters=800, lr=0.1, l2=1e-3, seed=0):
    rng = np.random.default_rng(seed)
    n, d = X.shape
    W1 = rng.normal(0, 0.3, (d, H)); b1 = np.zeros(H)
    W2 = rng.normal(0, 0.3, (H, 1)); b2 = 0.0
    for _ in range(iters):
        Z1 = X @ W1 + b1; A1 = np.maximum(0, Z1)
        z2 = np.clip(A1 @ W2[:, 0] + b2, -30, 30)
        p = 1 / (1 + np.exp(-z2)); g = (p - y) / n
        gW2 = A1.T @ g[:, None] + l2 * W2; gb2 = g.sum()
        dA1 = g[:, None] * W2[:, 0][None, :]; dZ1 = dA1 * (Z1 > 0)
        gW1 = X.T @ dZ1 + l2 * W1; gb1 = dZ1.sum(0)
        W1 -= lr * gW1; b1 -= lr * gb1; W2 -= lr * gW2; b2 -= lr * gb2

    def predict(Z):
        A1 = np.maximum(0, Z @ W1 + b1)
        return 1 / (1 + np.exp(-np.clip(A1 @ W2[:, 0] + b2, -30, 30)))
    return predict


def occlusion_value(predict, Xs):
    vals = np.zeros(N_FACTS)
    for f in range(N_FACTS):
        on = Xs.copy(); on[:, f] = 1.0
        off = Xs.copy(); off[:, f] = 0.0
        vals[f] = (predict(on) - predict(off)).mean()
    return vals


def dprime(v, pos, neg):
    s, d = v[pos], v[neg]
    return (s.mean() - d.mean()) / (np.sqrt(0.5 * (s.var() + d.var())) + 1e-9)


def average_precision(v):
    order = np.argsort(-v); lab = IS_STRUCT[order]
    hits = np.cumsum(lab); prec = hits / (np.arange(len(v)) + 1)
    return (prec * lab).sum() / max(1, lab.sum())


def main():
    SEEDS, N_EP = 20, 3000
    learners = ("logreg_MISMATCHED", "mlp_nonlinear")
    R = {k: {"dpc": [], "dpr": [], "ap": []} for k in learners}
    succ = []
    with np.errstate(all="ignore"):
        for s in range(SEEDS):
            rng = np.random.default_rng(5000 + s)
            X, y = gen(rng, N_EP)
            succ.append(y.mean())
            Xs = X[:800]
            preds = {"logreg_MISMATCHED": fit_logreg(X, y),
                     "mlp_nonlinear": fit_mlp(X, y, seed=s)}
            for k, pr in preds.items():
                v = occlusion_value(pr, Xs)
                R[k]["dpc"].append(dprime(v, IS_STRUCT, IS_CONF))
                R[k]["dpr"].append(dprime(v, IS_STRUCT, IS_RAND))
                R[k]["ap"].append(average_precision(v))

    print(f"Exp2.5 — model-class MISMATCH | seeds={SEEDS} episodes={N_EP} "
          f"| NONLINEAR (conjunctive) outcome | success {np.mean(succ):.2f}")
    print("value = occlusion attribution; structure revealed only via nonlinear "
          "recipe outcomes\n")
    print(f"{'learner':<20} {'dP(vs conf)':>12} {'dP(vs rand)':>12} {'AP':>8}")
    for k in learners:
        f = lambda m: np.mean(R[k][m])
        print(f"{k:<20} {f('dpc'):>12.2f} {f('dpr'):>12.2f} {f('ap'):>8.3f}")

    lc = np.mean(R["logreg_MISMATCHED"]["dpc"]); mc = np.mean(R["mlp_nonlinear"]["dpc"])
    print(f"\nRead: outcome is a nonlinear AND of structural pairs. A MISMATCHED "
          f"linear learner still assigns {'higher' if lc > 1 else 'no clearly higher'} "
          f"value to structural vs confounded (dP={lc:.2f}); the nonlinear MLP "
          f"recovers more (dP={mc:.2f}). If both stay well above ~1, the trained-"
          f"value result is NOT an artifact of matched model class. If linear "
          f"collapses and only MLP holds, a nonlinear value model is required.")


if __name__ == "__main__":
    main()
